#!/usr/bin/env python3
"""Grader for candidate simulation-3 (cold-chain depot network).
Usage: python grade.py <run-record.json>      (or: python grade.py --selftest)
Prints: {"task","score","total","detail"}. Self-contained; ground truth in key.json
next to this file (generated by generator.py, verified by oracle.py).

Points (hard difficulty, 4 depots x 3 checkpoints = 60 total):
  checkpoints : per (day, depot): on_hand AND backorders both exact -> 2 points,
                in_transit exact -> 1 point                          -> 36
                (on_hand > 0 and backorders > 0 are mutually exclusive in this
                system, so scoring them separately handed out ~15 free points to
                an all-zeros answer; paired they are worth ~3.)
  depots      : 1 point per (depot, field) exact match               -> 12
  central     : 2 points per field exact match                       ->  6
  same_day_served : exact                                            ->  3
  total_demand    : exact (a plain sum of the demand table)          ->  1
  fill_rate       : |diff| <= 0.0005 (i.e. the 4-dp value), no band  ->  2
Every item is graded independently, so a model that tracks three depots
correctly and botches one still scores ~70%. Missing/unparseable fields score 0.
detail carries: chance_floor (what an all-zeros answer scores on this key),
floor_adjusted ((score - floor) / (total - floor), clipped at 0),
first_checkpoint_with_error, depots_fully_correct_final, fill_rate_consistent
(does the reported fill_rate equal reported same_day_served / total_demand?),
format_deviation (set when the answer had to be recovered from text) and the
list of wrong fields.
"""
import ast
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "tasks"))
try:
    from _common import load_answer, emit
except ImportError:  # pragma: no cover - keep grader usable standalone
    def load_answer(path):
        rec = json.load(open(path))
        ans = rec.get("answer")
        if isinstance(ans, str):
            try:
                ans = json.loads(ans)
            except Exception:
                ans = {"_text": ans}
        return rec, (ans if isinstance(ans, dict) else {})

    def emit(task, score, total, detail):
        print(json.dumps({"task": task, "score": score, "total": total, "detail": detail}))

HERE = os.path.dirname(os.path.abspath(__file__))
TASK_ID = "S3"
KEY_PATH = os.environ.get("S3_KEY", os.path.join(HERE, "key.json"))

PTS_PAIR, PTS_TRANSIT = 2, 1
PTS_DEPOT_FIELD, PTS_CENTRAL_FIELD = 1, 2
PTS_SAME_DAY, PTS_DEMAND, PTS_FILL = 3, 1, 2
FILL_TOL = 0.0005

# accepted spellings of the three network-level fields (case/punctuation-insensitive)
ALIASES = {
    "same_day_served": ["same_day_served", "same_day_served_total", "sameday_served", "served_same_day",
                        "same_day_served_units", "same_day"],
    "total_demand": ["total_demand", "demand_total", "total_demanded", "demanded", "demand"],
    "fill_rate": ["fill_rate", "fillrate", "fill"],
}


# ---------------------------------------------------------------- tolerant parsing
def _balanced_objects(text):
    """Yield every balanced top-level {...} substring of text, in document order."""
    out = []
    i, n = 0, len(text)
    while i < n:
        if text[i] != "{":
            i += 1
            continue
        depth, in_str, esc, end = 0, False, False, None
        for j in range(i, n):
            c = text[j]
            if in_str:
                if esc:
                    esc = False
                elif c == "\\":
                    esc = True
                elif c == '"':
                    in_str = False
                continue
            if c == '"':
                in_str = True
            elif c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    end = j
                    break
        if end is None:          # unbalanced: skip this brace, try the next one
            i += 1
            continue
        out.append(text[i:end + 1])
        i = end + 1
    return out


def parse_text(text):
    """Recover an answer dict from prose / fenced / python-repr text.
    Candidates are considered in document order and the LAST one that carries the
    answer's top-level keys wins, so a draft object followed by a corrected one is
    graded on the correction (this mirrors the tournament's extractor rule)."""
    best = None
    for c in _balanced_objects(text):
        for loader in (json.loads, ast.literal_eval):
            try:
                v = loader(c)
            except Exception:
                continue
            if isinstance(v, dict) and ("checkpoints" in v or "depots" in v or "central" in v):
                if best is None or "checkpoints" in v or "checkpoints" not in best:
                    best = v
            break
    return best or {}


def _int(v):
    try:
        if isinstance(v, bool):
            return None
        f = float(str(v).replace(",", "").strip())
        if abs(f - round(f)) < 1e-6:
            return int(round(f))
    except Exception:
        pass
    return None


def _float(v):
    try:
        return float(str(v).replace(",", "").replace("%", "").strip())
    except Exception:
        return None


def _norm(k, strip_prefix=False):
    kk = re.sub(r"[^a-z0-9]", "", str(k).lower())
    if strip_prefix:
        # 'day15' / 'd15' / 'checkpoint15' -> '15'; 'depotB' / 'depot_b' -> 'b'
        m = re.match(r"^(?:checkpoint|day|depot|d)(\d+|[a-z])$", kk)
        if m:
            return m.group(1)
    return kk


def _get_ci(d, key):
    """Case/format-insensitive lookup: '10', 'day10', 'day_10', 'Day 10', 'd10', 'a', 'A' ...
    Prefixes are only stripped when looking up a day number or a depot letter."""
    if not isinstance(d, dict):
        return None
    if key in d:
        return d[key]
    strip = bool(re.fullmatch(r"\d+|[A-Za-z]", str(key)))
    want = _norm(key, strip)
    for k, v in d.items():
        if _norm(k, strip) == want:
            return v
    return None


def _get_alias(d, field):
    if not isinstance(d, dict):
        return None
    for a in ALIASES[field]:
        v = _get_ci(d, a)
        if v is not None:
            return v
    return None


# ---------------------------------------------------------------- grading
def _score(ans, key):
    detail = {"checkpoints": {}, "depots": {}, "central": {}, "network": {}}
    score = 0
    total = 0
    wrong = []

    # checkpoints: (on_hand, backorders) paired = 2 points, in_transit = 1 point
    ck_days = sorted(key["checkpoints"], key=int)
    depots = sorted(key["checkpoints"][ck_days[0]])
    first_bad_day = None
    got_ck = ans.get("checkpoints") if isinstance(ans, dict) else None
    if got_ck is None and isinstance(ans, dict):
        got_ck = _get_ci(ans, "checkpoints")
    per_day_max = len(depots) * (PTS_PAIR + PTS_TRANSIT)
    for day in ck_days:
        gd = _get_ci(got_ck, day)
        ok_day = 0
        for dep in depots:
            gdep = _get_ci(gd, dep)
            want = key["checkpoints"][day][dep]
            got_oh = _int(_get_ci(gdep, "on_hand"))
            got_bo = _int(_get_ci(gdep, "backorders"))
            got_it = _int(_get_ci(gdep, "in_transit"))
            total += PTS_PAIR
            if got_oh == want["on_hand"] and got_bo == want["backorders"]:
                score += PTS_PAIR
                ok_day += PTS_PAIR
            else:
                wrong.append(f"ck{day}.{dep}.on_hand/backorders: want {want['on_hand']}/{want['backorders']}"
                             f" got {got_oh}/{got_bo}")
            total += PTS_TRANSIT
            if got_it == want["in_transit"]:
                score += PTS_TRANSIT
                ok_day += PTS_TRANSIT
            else:
                wrong.append(f"ck{day}.{dep}.in_transit: want {want['in_transit']} got {got_it}")
        detail["checkpoints"][day] = f"{ok_day}/{per_day_max}"
        if ok_day < per_day_max and first_bad_day is None:
            first_bad_day = int(day)

    # per-depot totals: 1 point per field
    got_dep = _get_ci(ans, "depots")
    depots_fully_correct = 0
    last = ck_days[-1]
    for dep in depots:
        gdep = _get_ci(got_dep, dep)
        ok = 0
        for field, want in key["depots"][dep].items():
            total += PTS_DEPOT_FIELD
            got = _int(_get_ci(gdep, field))
            if got == want:
                score += PTS_DEPOT_FIELD
                ok += 1
            else:
                wrong.append(f"depots.{dep}.{field}: want {want} got {got}")
        detail["depots"][dep] = f"{ok}/{len(key['depots'][dep])}"
        gl = _get_ci(_get_ci(got_ck, last), dep)
        if ok == len(key["depots"][dep]) and all(
                _int(_get_ci(gl, f)) == w for f, w in key["checkpoints"][last][dep].items()):
            depots_fully_correct += 1

    # central: 2 points per field
    got_c = _get_ci(ans, "central")
    for field, want in key["central"].items():
        total += PTS_CENTRAL_FIELD
        got = _int(_get_ci(got_c, field))
        if got == want:
            score += PTS_CENTRAL_FIELD
            detail["central"][field] = "ok"
        else:
            detail["central"][field] = f"want {want} got {got}"
            wrong.append(f"central.{field}: want {want} got {got}")

    # network: same_day_served (3, exact), total_demand (1, exact), fill_rate (2, 4-dp exact)
    sds = _int(_get_alias(ans, "same_day_served"))
    dem = _int(_get_alias(ans, "total_demand"))
    fr = _float(_get_alias(ans, "fill_rate"))
    if fr is not None and 1.0 < fr <= 100.0:
        fr = fr / 100.0  # tolerate percentages
    total += PTS_SAME_DAY
    if sds == key["same_day_served"]:
        score += PTS_SAME_DAY
        detail["network"]["same_day_served"] = "ok"
    else:
        detail["network"]["same_day_served"] = f"want {key['same_day_served']} got {sds}"
        wrong.append(f"same_day_served: want {key['same_day_served']} got {sds}")
    total += PTS_DEMAND
    if dem == key["total_demand"]:
        score += PTS_DEMAND
        detail["network"]["total_demand"] = "ok"
    else:
        detail["network"]["total_demand"] = f"want {key['total_demand']} got {dem}"
        wrong.append(f"total_demand: want {key['total_demand']} got {dem}")
    total += PTS_FILL
    if fr is not None and abs(fr - key["fill_rate"]) <= FILL_TOL:
        score += PTS_FILL
        detail["network"]["fill_rate"] = "ok"
    else:
        detail["network"]["fill_rate"] = f"want {key['fill_rate']} got {fr}"
        wrong.append(f"fill_rate: want {key['fill_rate']} got {fr}")
    # diagnostic: is the reported fill_rate arithmetically consistent with the reported integers?
    if sds is not None and dem:
        detail["network"]["fill_rate_consistent"] = (fr is not None and abs(fr - round(sds / dem, 4)) <= FILL_TOL)
    else:
        detail["network"]["fill_rate_consistent"] = None

    detail["first_checkpoint_with_error"] = first_bad_day
    detail["depots_fully_correct_final"] = depots_fully_correct
    detail["wrong_fields"] = wrong[:24]
    return score, total, detail


def zeros_answer(key):
    """The zero-work baseline: every integer 0, fill_rate 0.0."""
    return {
        "checkpoints": {d: {dep: {"on_hand": 0, "backorders": 0, "in_transit": 0} for dep in c}
                        for d, c in key["checkpoints"].items()},
        "depots": {dep: {f: 0 for f in v} for dep, v in key["depots"].items()},
        "central": {f: 0 for f in key["central"]},
        "same_day_served": 0, "total_demand": 0, "fill_rate": 0.0,
    }


def grade(ans, key=None):
    format_deviation = None
    if not isinstance(ans, dict):
        ans = {}
    if "_text" in ans and len(ans) == 1:
        ans = parse_text(ans["_text"])
        format_deviation = "recovered-from-text"
    elif isinstance(ans, dict) and "checkpoints" not in ans:
        # unwrap {"answer": {...}} / {"result": {...}} style wrappers
        for w in ("answer", "result", "output", "response"):
            if isinstance(ans.get(w), dict) and "checkpoints" in ans[w]:
                ans = ans[w]
                format_deviation = f"unwrapped:{w}"
                break
    if key is None:
        key = json.load(open(KEY_PATH))
    score, total, detail = _score(ans, key)
    floor, _, _ = _score(zeros_answer(key), key)
    detail["chance_floor"] = floor
    detail["floor_adjusted"] = round(max(0, score - floor) / (total - floor), 4) if total > floor else None
    detail["format_deviation"] = format_deviation
    return score, total, detail


# ---------------------------------------------------------------- self-test
def _selftest():
    import copy
    key = json.load(open(KEY_PATH))
    out = {}
    s, t, d = grade(copy.deepcopy(key), key)
    out["key"] = (s, t)
    assert s == t, ("key must score full marks", s, t, d["wrong_fields"])
    # corrupted: depot D wrong from the second checkpoint on, plus fill_rate off by one unit
    bad = copy.deepcopy(key)
    days = sorted(bad["checkpoints"], key=int)
    dep = sorted(bad["depots"])[-1]
    for day in days[1:]:
        for f in bad["checkpoints"][day][dep]:
            bad["checkpoints"][day][dep][f] += 1
    bad["depots"][dep]["stockout_days"] += 1
    bad["same_day_served"] += 1
    bad["fill_rate"] = round(bad["same_day_served"] / bad["total_demand"], 4)
    s2, _, d2 = grade(bad, key)
    out["corrupted"] = s2
    assert s2 < s, "corrupted answer must score less"
    assert d2["first_checkpoint_with_error"] == int(days[1]), d2
    # empty answer
    s3, _, _ = grade({}, key)
    out["empty"] = s3
    assert s3 == 0
    # all-zeros floor is what detail reports
    s4, _, d4 = grade(zeros_answer(key), key)
    out["all_zeros"] = s4
    assert s4 == d4["chance_floor"], (s4, d4["chance_floor"])
    # old-style fill_rate near-miss (within 0.01 but not 0.0005) earns nothing for fill_rate
    near = copy.deepcopy(key)
    near["fill_rate"] = round(key["fill_rate"] + 0.004, 4)
    s5, _, d5 = grade(near, key)
    out["fill_rate_off_by_0.004"] = s5
    assert s5 == t - PTS_FILL and d5["network"]["fill_rate_consistent"] is False
    # 'd15'-style checkpoint keys, 'Day 22', lowercase depots and alias field names are accepted
    alt = copy.deepcopy(key)
    alt["checkpoints"] = {("d" + k if i == 0 else ("Day " + k if i == 1 else "day_" + k)):
                          {dep.lower(): v for dep, v in c.items()}
                          for i, (k, c) in enumerate(alt["checkpoints"].items())}
    alt["demand_total"] = alt.pop("total_demand")
    alt["same_day_served_total"] = alt.pop("same_day_served")
    alt["fill_rate"] = f"{key['fill_rate'] * 100:.2f}%"
    s6, _, d6 = grade(alt, key)
    out["alt_keys_and_percent"] = s6
    assert s6 == t, d6["wrong_fields"]
    # text recovery: a wrong draft object followed by the correct one -> the LAST wins
    draft = copy.deepcopy(key)
    draft["central"]["total_cancelled"] += 5
    text = "Here is my first pass:\n" + json.dumps(draft) + "\n\nCorrected:\n```json\n" + json.dumps(key) + "\n```\n"
    s7, _, d7 = grade({"_text": text}, key)
    out["text_draft_then_final"] = s7
    assert s7 == t and d7["format_deviation"] == "recovered-from-text", d7
    text2 = json.dumps(key) + "\nWait, I think total_cancelled is different:\n" + json.dumps(draft)
    s8, _, _ = grade({"_text": text2}, key)
    out["text_final_then_draft"] = s8
    assert s8 == t - PTS_CENTRAL_FIELD
    # wrapped answer
    s9, _, d9 = grade({"answer": copy.deepcopy(key)}, key)
    assert s9 == t and d9["format_deviation"] == "unwrapped:answer"
    # hedging does not pay: a list of alternatives in a cell scores as wrong
    hedge = copy.deepcopy(key)
    hedge["central"]["total_cancelled"] = [key["central"]["total_cancelled"], key["central"]["total_cancelled"] + 1]
    s10, _, _ = grade(hedge, key)
    assert s10 == t - PTS_CENTRAL_FIELD
    out["total"] = t
    out["chance_floor"] = d4["chance_floor"]
    print(json.dumps({"selftest": "ok", **out}))


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "--selftest":
        _selftest()
        sys.exit(0)
    _, ans = load_answer(sys.argv[1])
    s, t, d = grade(ans)
    emit(TASK_ID, s, t, d)
