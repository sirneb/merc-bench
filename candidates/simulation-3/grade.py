#!/usr/bin/env python3
"""Grader for candidate simulation-3 (cold-chain depot network).
Usage: python grade.py <run-record.json>
Prints: {"task","score","total","detail"}. Self-contained; ground truth in key.json
next to this file (generated by generator.py, verified by oracle.py).

Points (hard difficulty, 4 depots x 3 checkpoints = 60 total):
  checkpoints : 1 point per (day, depot, field) exact match          -> 36
  depots      : 1 point per (depot, field) exact match               -> 12
  central     : 2 points per field exact match                       ->  6
  fill_rate   : 6 if |diff| <= 0.0005, 3 if |diff| <= 0.01, else 0   ->  6
Every field is graded independently, so a model that tracks three depots
correctly and botches one still scores ~70%. Missing/unparseable fields score 0.
"""
import ast
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "tasks"))
try:
    from _common import load_answer, emit
except ImportError:  # pragma: no cover - keep grader usable standalone
    def load_answer(path):
        rec = json.load(open(path))
        ans = rec.get("answer")
        if isinstance(ans, str):
            try:
                ans = json.loads(ans)
            except Exception:
                ans = {"_text": ans}
        return rec, (ans if isinstance(ans, dict) else {})

    def emit(task, score, total, detail):
        print(json.dumps({"task": task, "score": score, "total": total, "detail": detail}))

HERE = os.path.dirname(os.path.abspath(__file__))
TASK_ID = "S3"


# ---------------------------------------------------------------- tolerant parsing
def _balanced_objects(text):
    """Yield every balanced {...} substring of text, longest first."""
    out = []
    for start, ch in enumerate(text):
        if ch != "{":
            continue
        depth, in_str, esc = 0, False, False
        for i in range(start, len(text)):
            c = text[i]
            if in_str:
                if esc:
                    esc = False
                elif c == "\\":
                    esc = True
                elif c == '"':
                    in_str = False
                continue
            if c == '"':
                in_str = True
            elif c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    out.append(text[start:i + 1])
                    break
    out.sort(key=len, reverse=True)
    return out


def parse_text(text):
    """Recover an answer dict from prose / fenced / python-repr text."""
    cands = []
    m = re.findall(r"```(?:json)?\s*(\{.*?\})\s*```", text, re.S)
    cands += m
    cands += _balanced_objects(text)
    for c in cands:
        for loader in (json.loads, ast.literal_eval):
            try:
                v = loader(c)
            except Exception:
                continue
            if isinstance(v, dict) and ("checkpoints" in v or "depots" in v or "central" in v):
                return v
    return {}


def _int(v):
    try:
        if isinstance(v, bool):
            return None
        f = float(str(v).replace(",", "").strip())
        if abs(f - round(f)) < 1e-6:
            return int(round(f))
    except Exception:
        pass
    return None


def _float(v):
    try:
        return float(str(v).replace(",", "").replace("%", "").strip())
    except Exception:
        return None


def _get_ci(d, key):
    """Case/format-insensitive lookup: '10', 'day10', 'day_10', 'Day 10', 'a', 'A' ..."""
    if not isinstance(d, dict):
        return None
    if key in d:
        return d[key]
    want = re.sub(r"[^a-z0-9]", "", str(key).lower())
    for k, v in d.items():
        kk = re.sub(r"[^a-z0-9]", "", str(k).lower())
        if kk == want or kk == "day" + want or kk == "depot" + want:
            return v
    return None


# ---------------------------------------------------------------- grading
def grade(ans):
    if "_text" in ans and len(ans) == 1:
        ans = parse_text(ans["_text"])
    key = json.load(open(os.path.join(HERE, "key.json")))
    detail = {"checkpoints": {}, "depots": {}, "central": {}, "fill_rate": {}}
    score = 0
    total = 0
    wrong = []

    # checkpoints: 1 point per field
    ck_days = sorted(key["checkpoints"], key=int)
    depots = sorted(key["checkpoints"][ck_days[0]])
    first_bad_day = None
    got_ck = ans.get("checkpoints", {})
    for day in ck_days:
        gd = _get_ci(got_ck, day)
        ok_day = 0
        for dep in depots:
            gdep = _get_ci(gd, dep)
            for field, want in key["checkpoints"][day][dep].items():
                total += 1
                got = _int(_get_ci(gdep, field))
                if got == want:
                    score += 1
                    ok_day += 1
                else:
                    wrong.append(f"ck{day}.{dep}.{field}: want {want} got {got}")
        detail["checkpoints"][day] = f"{ok_day}/{len(depots) * 3}"
        if ok_day < len(depots) * 3 and first_bad_day is None:
            first_bad_day = int(day)

    # per-depot totals: 1 point per field
    got_dep = ans.get("depots", {})
    depots_fully_correct = 0
    for dep in depots:
        gdep = _get_ci(got_dep, dep)
        ok = 0
        for field, want in key["depots"][dep].items():
            total += 1
            got = _int(_get_ci(gdep, field))
            if got == want:
                score += 1
                ok += 1
            else:
                wrong.append(f"depots.{dep}.{field}: want {want} got {got}")
        detail["depots"][dep] = f"{ok}/3"
        # "fully correct at final day": all final-checkpoint fields + all totals
        last = ck_days[-1]
        gl = _get_ci(_get_ci(got_ck, last), dep)
        if ok == 3 and all(_int(_get_ci(gl, f)) == w for f, w in key["checkpoints"][last][dep].items()):
            depots_fully_correct += 1

    # central: 2 points per field
    got_c = ans.get("central", {})
    for field, want in key["central"].items():
        total += 2
        got = _int(_get_ci(got_c, field))
        if got == want:
            score += 2
            detail["central"][field] = "ok"
        else:
            detail["central"][field] = f"want {want} got {got}"

    # fill rate: 6 / 3 / 0
    total += 6
    fr = _float(ans.get("fill_rate"))
    want = key["fill_rate"]
    if fr is not None and fr > 1.0 and fr <= 100.0:
        fr = fr / 100.0  # tolerate percentages
    if fr is not None and abs(fr - want) <= 0.0005:
        score += 6
        detail["fill_rate"] = "exact"
    elif fr is not None and abs(fr - want) <= 0.01:
        score += 3
        detail["fill_rate"] = f"close (want {want} got {fr})"
    else:
        detail["fill_rate"] = f"want {want} got {fr}"

    detail["first_checkpoint_with_error"] = first_bad_day
    detail["depots_fully_correct_final"] = depots_fully_correct
    detail["wrong_fields"] = wrong[:20]
    return score, total, detail


if __name__ == "__main__":
    _, ans = load_answer(sys.argv[1])
    s, t, d = grade(ans)
    emit(TASK_ID, s, t, d)
