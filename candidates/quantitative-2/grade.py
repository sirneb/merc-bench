#!/usr/bin/env python3
"""Grader for candidate Q2 (crew roster across fictional DST).
Usage: python grade.py <run-record.json>
Prints: {"task","score","total","detail"}. Self-contained; ground truth in key.json
next to this file (generated by generator.py, verified by oracle.py).

Scoring (default config: 60 points)
  legs            1.0 per leg: both arr_local and arr_utc exact to the minute;
                  0.5 if exactly one of the two is right (right instant / wrong
                  rendering, or vice versa)               -> 40
  duty_periods    1.0 per key period whose `minutes` is exact, 0.5 if within
                  +/-60 min (a single DST-hour slip); periods are matched to the
                  key by nearest start_utc (within 3 h), so one wrong split does
                  not zero the rest                      -> 10 (n key periods)
  violations      4 x Jaccard(model set, key set)        -> 4
  home_base_month_minutes  6 exact, 3 if within 1 %      -> 6
Datetime strings are parsed tolerantly (T separator, seconds, Z/UTC suffix).
"""
import json
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)),
                                "..", "..", "tasks"))
from _common import load_answer, emit  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
DT_RE = re.compile(r"(\d{4})-(\d{1,2})-(\d{1,2})[ T](\d{1,2}):(\d{2})")
ID_RE = re.compile(r"^\s*([LD])\s*0*(\d+)\s*$", re.I)

_CUM = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334]


def to_minutes(s):
    """'2027-09-14 03:15' (tolerant) -> integer minutes on a fixed calendar;
    None when unparseable. Only differences between values are used."""
    if s is None:
        return None
    m = DT_RE.search(str(s))
    if not m:
        return None
    y, mo, d, h, mi = map(int, m.groups())
    if not (1 <= mo <= 12 and 1 <= d <= 31 and h < 24 and mi < 60):
        return None
    leap = 1 if (mo > 2 and y % 4 == 0 and (y % 100 != 0 or y % 400 == 0)) else 0
    days = y * 366 + _CUM[mo - 1] + leap + d       # monotone enough for diffs
    return days * 1440 + h * 60 + mi


def norm_id(v, prefix):
    m = ID_RE.match(str(v))
    if m and m.group(1).upper() == prefix:
        return "%s%s" % (prefix, int(m.group(2)))
    return None


def leg_key(v):
    n = norm_id(v, "L")
    return "L%02d" % int(n[1:]) if n else None


def same_minute(a, b):
    x, y = to_minutes(a), to_minutes(b)
    return x is not None and x == y


def extract_from_text(text):
    """Best-effort recovery when the answer arrived as prose/wrapped JSON."""
    try:
        i, j = text.index("{"), text.rindex("}")
        obj = json.loads(text[i:j + 1])
        if isinstance(obj, dict):
            return obj
    except Exception:
        pass
    ans = {"legs": [], "duty_periods": [], "violations": []}
    pat = re.compile(r'"?(L\s*\d{1,3})"?\s*[:,]?[^\n{]*?'
                     r'(?:arr_utc"?\s*[:=]\s*"?([\d\-T: ]+))[^\n}]*?'
                     r'(?:arr_local"?\s*[:=]\s*"?([\d\-T: ]+))', re.I)
    for lid, u, l in pat.findall(text):
        ans["legs"].append({"id": lid, "arr_utc": u, "arr_local": l})
    m = re.search(r'home_base_month_minutes"?\s*[:=]\s*(\d+)', text)
    if m:
        ans["home_base_month_minutes"] = int(m.group(1))
    return ans


def grade(ans):
    key = json.load(open(os.path.join(HERE, "key.json")))
    chain = key.get("config", {}).get("chain", True)
    if "_text" in ans:
        ans = extract_from_text(ans["_text"])
    detail = {}
    score = 0.0

    # ---- legs -------------------------------------------------------------
    got = {}
    for lg in ans.get("legs", []) or []:
        if isinstance(lg, dict):
            k = leg_key(lg.get("id"))
            if k and k not in got:
                got[k] = lg
    leg_pts, misses = 0.0, {}
    near_pts, near_n, far_pts, far_n = 0.0, 0, 0.0, 0
    for k in key["legs"]:
        g = got.get(k["id"], {})
        lo = same_minute(g.get("arr_local"), k["arr_local"])
        uo = same_minute(g.get("arr_utc"), k["arr_utc"])
        p = 1.0 if (lo and uo) else 0.5 if (lo or uo) else 0.0
        leg_pts += p
        if k.get("near_transition"):
            near_pts += p
            near_n += 1
        else:
            far_pts += p
            far_n += 1
        if p < 1.0:
            misses[k["id"]] = {"want": [k["arr_local"], k["arr_utc"]],
                               "got": [g.get("arr_local"), g.get("arr_utc")],
                               "near_transition": k.get("near_transition")}
    score += leg_pts
    total = len(key["legs"])
    detail["legs"] = {"points": leg_pts, "of": len(key["legs"]),
                      "near_transition": [near_pts, near_n],
                      "other": [far_pts, far_n], "misses": misses}

    # ---- duty periods -------------------------------------------------------
    if chain:
        kd = key["duty_periods"]
        md = []
        for d in ans.get("duty_periods", []) or []:
            if not isinstance(d, dict):
                continue
            s, e = to_minutes(d.get("start_utc")), to_minutes(d.get("end_utc"))
            mins = d.get("minutes")
            try:
                mins = int(round(float(mins)))
            except Exception:
                mins = (e - s) if (s is not None and e is not None) else None
            md.append({"start": s, "end": e, "minutes": mins, "used": False})
        duty_pts, drows = 0.0, {}
        for k in kd:
            ks = to_minutes(k["start_utc"])
            best, bd = None, None
            for m in md:
                if m["used"] or m["start"] is None:
                    continue
                dist = abs(m["start"] - ks)
                if dist <= 180 and (bd is None or dist < bd):
                    best, bd = m, dist
            p = 0.0
            if best is not None:
                best["used"] = True
                if best["minutes"] == k["minutes"]:
                    p = 1.0
                elif best["minutes"] is not None and \
                        abs(best["minutes"] - k["minutes"]) <= 60:
                    p = 0.5
            duty_pts += p
            drows[k["id"]] = {"want": k["minutes"],
                              "got": best["minutes"] if best else None,
                              "points": p}
        score += duty_pts
        total += len(kd)
        detail["duty_periods"] = {"points": duty_pts, "of": len(kd),
                                  "model_count": len(md), "rows": drows}

        # ---- violations (Jaccard) ------------------------------------------
        want = {norm_id(v, "D") for v in key["violations"]}
        have = {norm_id(v, "D") for v in (ans.get("violations", []) or [])
                if norm_id(v, "D")}
        if not want and not have:
            jac = 1.0
        else:
            jac = len(want & have) / float(len(want | have))
        vp = round(4 * jac, 3)
        score += vp
        total += 4
        detail["violations"] = {"points": vp, "of": 4, "want": sorted(want),
                                "got": sorted(have)}

    # ---- home-base month minutes -------------------------------------------
    kh = key["home_base_month_minutes"]
    try:
        gh = float(str(ans.get("home_base_month_minutes")).replace(",", ""))
    except Exception:
        gh = None
    hp = 0.0
    if gh is not None:
        if int(round(gh)) == kh:
            hp = 6.0
        elif abs(gh - kh) <= 0.01 * kh:
            hp = 3.0
    score += hp
    total += 6
    detail["home_base_month_minutes"] = {"points": hp, "of": 6, "want": kh,
                                         "got": ans.get("home_base_month_minutes")}
    score = round(score, 3)
    if score == int(score):
        score = int(score)
    return score, total, detail


if __name__ == "__main__":
    _, ans = load_answer(sys.argv[1])
    s, t, d = grade(ans)
    emit("Q2", s, t, d)
